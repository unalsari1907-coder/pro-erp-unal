-- Vade takip nesnesi kurulumlara göre TABLE veya VIEW olabilir.
-- Hiç yoksa tablo oluşturulur; normal VIEW ise mevcut yapıya dokunulmaz.
do $$
declare
  v_relkind "char";
begin
  select c.relkind
    into v_relkind
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relname = 'erp_vade_takip';

  if v_relkind is null then
    execute $sql$
      create table public.erp_vade_takip (
        vade_id bigint generated by default as identity primary key,
        cari_id bigint,
        cari_unvan text,
        belge_tipi text,
        belge_id bigint,
        fatura_no text,
        yon text,
        fatura_tarihi date,
        vade_tarihi date,
        toplam_tutar numeric(18,2) default 0,
        odenen_tutar numeric(18,2) default 0,
        kalan_tutar numeric(18,2) default 0,
        gecikme_gun integer default 0,
        durum text default 'ACIK',
        created_at timestamptz default now()
      )
    $sql$;
    v_relkind := 'r';
    raise notice 'erp_vade_takip bulunamadı; TABLE olarak oluşturuldu.';
  elsif v_relkind = 'v' then
    raise notice 'erp_vade_takip mevcut bir VIEW; tabloya çevrilmedi ve VIEW korunuyor.';
  elsif v_relkind = 'm' then
    raise notice 'erp_vade_takip MATERIALIZED VIEW olarak mevcut.';
  else
    raise notice 'erp_vade_takip mevcut relation tipi: %', v_relkind;
  end if;

  -- Normal tablo/partitioned tablo/materialized view üzerinde index oluşturulabilir.
  if v_relkind in ('r','p','m') then
    execute 'create index if not exists idx_erp_vade_takip_vade on public.erp_vade_takip(vade_tarihi)';
    execute 'create index if not exists idx_erp_vade_takip_cari on public.erp_vade_takip(cari_id)';
  end if;
end $$;

-- Mizan görünümü: muhasebe fiş satırları üzerinden hesap bazında borç/alacak/bakiye.
create or replace view public.erp_mizan as
select
  s.hesap_kodu,
  coalesce(h.hesap_adi, '-') as hesap_adi,
  coalesce(h.hesap_tipi, '-') as hesap_tipi,
  coalesce(sum(s.borc),0)::numeric(18,2) as borc,
  coalesce(sum(s.alacak),0)::numeric(18,2) as alacak,
  (coalesce(sum(s.borc),0)-coalesce(sum(s.alacak),0))::numeric(18,2) as bakiye
from public.erp_muhasebe_fis_satirlari s
left join public.erp_hesap_plani h on h.hesap_kodu=s.hesap_kodu
group by s.hesap_kodu,h.hesap_adi,h.hesap_tipi;

-- Fiş satırı değiştiğinde üst fiş toplamlarını otomatik eşitle.
create or replace function public.erp_muhasebe_fis_toplam_guncelle()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare v_fis bigint;
begin
  if TG_OP = 'DELETE' then
    v_fis := old.fis_id;
  else
    v_fis := new.fis_id;
  end if;
  update public.erp_muhasebe_fisleri f
  set borc_toplam = coalesce((select sum(borc) from public.erp_muhasebe_fis_satirlari where fis_id=v_fis),0),
      alacak_toplam = coalesce((select sum(alacak) from public.erp_muhasebe_fis_satirlari where fis_id=v_fis),0)
  where f.fis_id=v_fis;
  if TG_OP = 'DELETE' then
    return old;
  end if;
  return new;
end $$;

drop trigger if exists trg_erp_muhasebe_fis_toplam on public.erp_muhasebe_fis_satirlari;
create trigger trg_erp_muhasebe_fis_toplam
after insert or update or delete on public.erp_muhasebe_fis_satirlari
for each row execute function public.erp_muhasebe_fis_toplam_guncelle();

