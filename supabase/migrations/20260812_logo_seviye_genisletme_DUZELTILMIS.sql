-- Geçiş dönemi RLS politikaları. Güvenli giriş zorunlu hale getirildiğinde hardening migration uygulanmalı.
-- RLS yalnız TABLE / PARTITIONED TABLE üzerinde uygulanır; VIEW nesneleri güvenle atlanır.
do $$
declare
  t text;
  v_relkind "char";
begin
  foreach t in array array['erp_belge_baglantilari','erp_kur_farki_fisleri','erp_sistem_kontrol_log','erp_vade_takip'] loop
    select c.relkind
      into v_relkind
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname = t;

    if v_relkind in ('r','p') then
      execute format('alter table public.%I enable row level security', t);
      execute format('drop policy if exists "pro_erp_gecis_%s" on public.%I', t, t);
      execute format('create policy "pro_erp_gecis_%s" on public.%I for all to anon, authenticated using (true) with check (true)', t, t);
    else
      raise notice '% için RLS atlandı. Relation tipi: %', t, coalesce(v_relkind::text,'yok');
    end if;
  end loop;
end $$;
