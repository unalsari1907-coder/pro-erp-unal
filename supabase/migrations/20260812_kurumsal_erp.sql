create table if not exists public.erp_seri_lot (
  seri_lot_id bigint generated by default as identity primary key,
  stok_id bigint,
  uretici_kodu text,
  seri_no text,
  lot_no text,
  depo text,
  raf text,
  miktar numeric(18,3) default 1,
  son_kullanma_tarihi date,
  durum text default 'STOKTA',
  olusturma_tarihi timestamptz default now(),
  created_at timestamptz default now()
);
create index if not exists idx_erp_seri_lot_stok on public.erp_seri_lot(stok_id);
create index if not exists idx_erp_seri_lot_seri on public.erp_seri_lot(seri_no);

create table if not exists public.erp_fiyat_kurallari (
  kural_id bigint generated by default as identity primary key,
  kural_adi text not null,
