-- PRO ERP Kurumsal / Yedek Parça ERP genişletme paketi
-- Mevcut tabloları silmez. CREATE TABLE IF NOT EXISTS kullanır.

create table if not exists public.erp_teklifler (
  teklif_id bigint generated by default as identity primary key,
  belge_no text unique,
  tarih date default current_date,
  cari_unvan text,
  para_birimi text default 'TRY',
  kur numeric(18,6) default 1,
  toplam numeric(18,2) default 0,
  durum text default 'HAZIR',
  gecerlilik_tarihi date,
  aciklama text,
  created_at timestamptz default now()
);

create table if not exists public.erp_hesap_plani (
  hesap_id bigint generated by default as identity primary key,
  hesap_kodu text unique not null,
  hesap_adi text not null,
  hesap_tipi text,
  ust_hesap_kodu text,
  aktif boolean default true,
  created_at timestamptz default now()
);

create table if not exists public.erp_muhasebe_fisleri (
  fis_id bigint generated by default as identity primary key,
  fis_no text unique,
  tarih date default current_date,
  fis_tipi text default 'MAHSUP',
  aciklama text,
  borc_toplam numeric(18,2) default 0,
  alacak_toplam numeric(18,2) default 0,
  durum text default 'TASLAK',
  created_at timestamptz default now(),
  constraint erp_muhasebe_fis_denge check (borc_toplam >= 0 and alacak_toplam >= 0)
);

create table if not exists public.erp_cek_senet (
  evrak_id bigint generated by default as identity primary key,
  evrak_tipi text default 'ÇEK',
  evrak_no text,
  cari_unvan text,
  banka text,
  vade_tarihi date,
  tutar numeric(18,2) default 0,
  para_birimi text default 'TRY',
  durum text default 'PORTFOYDE',
  aciklama text,
  created_at timestamptz default now()
);
create index if not exists idx_erp_cek_senet_vade on public.erp_cek_senet(vade_tarihi);

create table if not exists public.erp_doviz_kurlari (
  kur_id bigint generated by default as identity primary key,
  tarih date default current_date,
  para_birimi text not null,
  alis numeric(18,6) default 0,
  satis numeric(18,6) default 0,
  efektif_alis numeric(18,6) default 0,
  efektif_satis numeric(18,6) default 0,
  kaynak text default 'MANUEL',
  created_at timestamptz default now(),
  unique(tarih, para_birimi)
);

create table if not exists public.erp_e_belgeler (
  ebelge_id bigint generated by default as identity primary key,
  belge_tipi text default 'E-FATURA',
  belge_no text,
  cari_unvan text,
  vergi_no text,
  olusturma_tarihi timestamptz default now(),
  durum text default 'HAZIR',
  entegrator text,
  uuid text,
  hata_mesaji text,
  created_at timestamptz default now()
);

create table if not exists public.erp_satin_alma_talepleri (
  talep_id bigint generated by default as identity primary key,
  talep_no text unique,
  tarih date default current_date,
  talep_eden text,
  depo text,
  oncelik text default 'NORMAL',
  durum text default 'BEKLIYOR',
  aciklama text,
  created_at timestamptz default now()
);

create table if not exists public.erp_onaylar (
  onay_id bigint generated by default as identity primary key,
  onay_tipi text,
  referans_no text,
  olusturma_tarihi timestamptz default now(),
  isteyen text,
  onaylayan text,
  durum text default 'BEKLIYOR',
  aciklama text,
  created_at timestamptz default now()
